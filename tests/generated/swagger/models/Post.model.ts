import { IsInt, IsDefined, IsDate, IsString, IsOptional, IsBoolean, IsNumber } from "class-validator";
import { ApiProperty } from "@nestjs/swagger";
import { User } from "./";

export class Post {
    @IsDefined()
    @ApiProperty({ example: 'Generated by autoincrement', type: "integer" })
    @IsInt()
    id!: number;

    @IsDefined()
    @ApiProperty({ example: 'Generated by now', type: "string", format: "date-time" })
    @IsDate()
    createdAt!: Date;

    @IsDefined()
    @ApiProperty({ type: "string", format: "date-time" })
    @IsDate()
    updatedAt!: Date;

    @IsDefined()
    @ApiProperty({ type: "string" })
    @IsString()
    title!: string;

    @IsOptional()
    @ApiProperty({ type: "string", required: false })
    @IsString()
    content?: string | null;

    @IsDefined()
    @ApiProperty({ example: false, type: "boolean" })
    @IsBoolean()
    published!: boolean;

    @IsDefined()
    @ApiProperty({ example: 0, type: "integer" })
    @IsInt()
    viewCount!: number;

    @IsOptional()
    @ApiProperty({ required: false, type: () => User })
    author?: User | null;

    @IsOptional()
    @ApiProperty({ type: "integer", required: false })
    @IsInt()
    authorId?: number | null;

    @IsDefined()
    @ApiProperty({ type: "number" })
    @IsNumber()
    rating!: number;
}
